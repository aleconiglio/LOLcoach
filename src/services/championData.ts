/**
 * Returns Riot DataDragon CDN Champion Icon URL
 */
export const getChampionIconUrl = (championName: string): string => {
  if (!championName) return '';

  // Normalize champion name for DataDragon API format
  const found = LOL_CHAMPIONS.find(
    (c) =>
      c.name.toLowerCase() === championName.toLowerCase() ||
      c.id.toLowerCase() === championName.toLowerCase()
  );

  let key = found ? found.id : championName.replace(/[^a-zA-Z0-9]/g, '');

  // Handle special Riot DataDragon keys
  const specialMap: Record<string, string> = {
    wukong: 'MonkeyKing',
    leblanc: 'Leblanc',
    khazix: 'Khazix',
    chogath: 'Chogath',
    velkoz: 'Velkoz',
    kaisa: 'Kaisa',
    belveth: 'Belveth',
    ksante: 'KSante',
    reksai: 'RekSai',
    nunu: 'Nunu',
    renata: 'Renata',
    drmundo: 'DrMundo',
    jarvaniv: 'JarvanIV',
    masteryi: 'MasterYi',
    tahmkench: 'TahmKench',
    leesin: 'LeeSin',
    missfortune: 'MissFortune',
    twistedfate: 'TwistedFate',
    xinzhao: 'XinZhao',
  };

  const lowerKey = key.toLowerCase();
  if (specialMap[lowerKey]) {
    key = specialMap[lowerKey];
  } else {
    // Capitalize first letter
    key = key.charAt(0).toUpperCase() + key.slice(1);
  }

  return `https://ddragon.leagueoflegends.com/cdn/15.3.1/img/champion/${key}.png`;
};

/**
 * Secondary fallback champion icon URL from Community Dragon CDN
 */
export const getChampionFallbackIconUrl = (championName: string): string => {
  if (!championName) return '';
  const found = LOL_CHAMPIONS.find(
    (c) =>
      c.name.toLowerCase() === championName.toLowerCase() ||
      c.id.toLowerCase() === championName.toLowerCase()
  );
  let key = found ? found.id : championName.replace(/[^a-zA-Z0-9]/g, '');
  return `https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/v1/champion-icons/${key}.png`;
};

/**
 * Robust image error handler that tries CommunityDragon fallback before hiding
 */
export const handleChampionImageError = (
  e: React.SyntheticEvent<HTMLImageElement, Event>,
  championName: string
) => {
  const target = e.currentTarget;
  if (!target.dataset.triedFallback) {
    target.dataset.triedFallback = 'true';
    target.src = getChampionFallbackIconUrl(championName);
  } else {
    target.style.display = 'none';
  }
};

/**
 * Returns Riot DataDragon CDN Item Icon URL
 */
export const getItemIconUrl = (itemId: number): string => {
  if (!itemId || itemId === 0) return '';
  return `https://ddragon.leagueoflegends.com/cdn/15.3.1/img/item/${itemId}.png`;
};
